import { expect, it } from "vitest";
import { clientIp } from "../client-ip.js";
it.each([
  ["203.0.113.9", "198.51.100.1", [], "203.0.113.9"],
  ["10.0.0.2", "198.51.100.1, 10.0.0.3", ["10.0.0.2", "10.0.0.3"], "198.51.100.1"],
  ["10.0.0.2", "192.0.2.8, 198.51.100.1, 10.0.0.3", ["10.0.0.2", "10.0.0.3"], "198.51.100.1"],
  ["10.0.0.2", undefined, ["10.0.0.2"], "10.0.0.2"],
  ["10.0.0.2", " 198.51.100.1 , 10.0.0.3 ", ["10.0.0.2", "10.0.0.3"], "198.51.100.1"],
  ["::ffff:10.0.0.2", "198.51.100.1", ["10.0.0.2"], "198.51.100.1"],
  ["2001:db8::2", "2001:db8::1", ["2001:db8::2"], "2001:db8::1"],
  ["10.0.0.2", "198.51.100.1, unknown", ["10.0.0.2"], "10.0.0.2"],
  ["10.0.0.2", "", ["10.0.0.2"], "10.0.0.2"],
  ["10.0.0.2", "10.0.0.3", ["10.0.0.2", "10.0.0.3"], "10.0.0.3"],
] as const)(
  "직접 연결과 오른쪽 프록시 경계로 클라이언트를 고른다: %s / %s",
  (remote, forwarded, trusted, expected) => {
    expect(clientIp(remote, forwarded, trusted)).toBe(expected);
  },
);
